package Strings;

public interface OperationsInString {
    public static void main(String[] args) {
        System.out.print('a' + 'b');
        System.out.print("a" + "b");
        System.out.print('a' + 3);
        System.out.print((char)('a' + 3));
        System.out.print("a" + 1);
        System.out.print("kalyan" + new Integer(78));
    }
}
